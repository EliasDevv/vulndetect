def tab_rq3_stages(c: dict, d: dict) -> str:
    """Macro-F1 and changed verdicts of the two Triple-Agent stages per seed, GAN final beside."""
    st = d["triple_agent"]["stages"]
    gan = dict(
        zip(
            c["approaches"]["gan/final"]["seeds"],
            c["approaches"]["gan/final"]["macro"]["f1"]["values"],
            strict=True,
        )
    )

    def share(run: dict) -> float:
        return run["n_validator_changed_detector"] / run["n_both_readable"]

    rows = [
        r"\begin{tabular}{@{}lccccc@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Macro-F1} & "
        r"\multicolumn{2}{c}{\begin{tabular}[b]{@{}c@{}}Verdicts changed\\by the Validator"
        r"\end{tabular}} \\",
        r"\cmidrule(lr){2-4}\cmidrule(l){5-6}",
        r"Seed & Triple final & \begin{tabular}[b]{@{}c@{}}Detector\\stage alone\end{tabular} "
        r"& GAN final & round 0 & final \\",
        r"\midrule",
    ]
    cols: list[list[float]] = [[], [], [], [], []]
    for seed in (42, 43, 44):
        r0, fin = st[f"round0000/seed{seed}"], st[f"final/seed{seed}"]
        vals = [
            fin["validator"]["macro_f1"],
            fin["detector"]["macro_f1"],
            gan[seed],
            share(r0),
            share(fin),
        ]
        for col, v in zip(cols, vals, strict=True):
            col.append(v)
        rows.append(f"{seed} & " + " & ".join(f"{v:.3f}" for v in vals) + r" \\")
    rows.append(r"\midrule")
    rows.append("Mean & " + " & ".join(f"{statistics.fmean(col):.3f}" for col in cols) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


def tab_cost(c: dict, d: dict) -> str:
    """Cost table with model calls, output tokens and GPU hours per approach."""
    cost = d["cost"]
    q = cost["queue_hours"]

    def hours(targets: list[str]) -> str:
        vals = [h for t in targets for h in q.get(t, [])]
        return f"$\\approx$\\,{statistics.fmean(vals):.1f}" if vals else "--"

    sft_train_h = statistics.fmean(v for v in cost["sft_training_seconds"].values()) / 3600
    loop_h = statistics.fmean(cost["gan_loop_hours"].values())
    # test runs of seeds 43/44 evaluate two snapshots, hence h / 2
    gan_eval = [h / 2 for t in ("gan-eval-seed43", "gan-eval-seed44") for h in q.get(t, [])]
    # SFT eval hours of seeds 43/44 come from the CSV gap sft_train -> sft
    sft_eval = [
        g["hours_since_previous_row"]
        for g in cost["csv_gaps_plausibility"]
        if g["approach"] == "sft" and g["seed"] in ("43", "44")
    ]
    triple_eval = [
        h / 2
        for t in ("triple_agent-eval-seed43", "triple_agent-eval-seed44")
        for h in q.get(t, [])
    ]
    triple_loop_h = statistics.fmean(cost["triple_loop_hours"].values())
    tok = cost["output_tokens_per_instance"]

    def approx(vals: list[float]) -> str:
        return f"$\\approx$\\,{statistics.fmean(vals):.1f}" if vals else "--"

    rows = [
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r"Approach & Calls & Output tokens & GPU-h per run & One-off GPU-h \\",
        r"\midrule",
        f"Baseline & 1 & {tok['baseline']['mean']:.0f} & "
        f"{hours(['baseline-seed43', 'baseline-seed44'])} & -- \\\\",
        f"RAG & 1 & {tok['rag']['mean']:.0f} & {hours(['rag-seed43', 'rag-seed44'])} & -- \\\\",
        f"SFT & 1 & {tok['sft']['mean']:.0f} & {approx(sft_eval)} & "
        f"{sft_train_h:.2f} (training) \\\\",
        f"Dual-Agent & 2 & {tok['dual_agent']['mean']:.0f} & "
        f"{hours(['dual_agent-seed43', 'dual_agent-seed44'])} & -- \\\\",
        f"GAN final & 1 & {tok['gan/final']['mean']:.0f} & {approx(gan_eval)} & "
        f"{loop_h:.1f} (loop) \\\\",
        f"Triple-Agent final & 2 & {tok['triple_agent/final']['mean']:.0f} & "
        f"{approx(triple_eval)} & {triple_loop_h:.1f} (loop) \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    return "\n".join(rows)


def tab_per_cwe_f1(c: dict) -> str:
    """Per-CWE F1 of the six approaches, with macro and micro aggregates below."""
    names = ALL
    cwes = sorted(c["approaches"]["baseline"]["per_cwe"])
    rows = [
        r"\begin{tabular}{@{}l" + "c" * len(names) + "@{}}",
        r"\toprule",
        "CWE & " + " & ".join(NAMES[n].replace(" final", "") for n in names) + r" \\",
        r"\midrule",
    ]
    for cwe in cwes:
        cells = [ms(c["approaches"][n]["per_cwe"][cwe]["f1"]) for n in names]
        n_cwe = c["approaches"]["baseline"]["per_cwe"][cwe]["n"]
        rows.append(f"{cwe} ($n={n_cwe}$) & " + " & ".join(cells) + r" \\")
    rows.append(r"\midrule")
    for agg, label in (("macro", "All (macro)"), ("micro", "All (micro)")):
        cells = [ms(c["approaches"][n][agg]["f1"]) for n in names]
        rows.append(f"{label} & " + " & ".join(cells) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


_LATEX_ESCAPES = {
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def latex_escape(text: str) -> str:
    """Escape LaTeX special characters in plain text."""
    return "".join(_LATEX_ESCAPES.get(ch, ch) for ch in text)


def app_memories(d: dict) -> str:
    """Final strategy memories of the GAN for seed 42 as enumerate lists."""
    out = []
    for memories, role, title in (
        (d["final_memories"], "s_d", "GAN, Detector strategies $S_D$"),
        (d["final_memories"], "s_g", "GAN, Generator strategies $S_G$"),
    ):
        for seed in ("42",):
            entries = memories[f"{role}/seed{seed}"]
            out.append(f"\\paragraph{{{title}, seed {seed}.}}")
            out.append(r"\begin{enumerate}")
            for e in entries:
                if e.startswith("**") and "**" in e[2:]:
                    name, rest = e[2:].split("**", 1)
                    item = f"\\emph{{{latex_escape(name)}}}{latex_escape(rest)}"
                else:
                    item = latex_escape(e)
                out.append(f"  \\item {item}")
            out.append(r"\end{enumerate}")
    return "\n".join(out) + "\n"


def main() -> None:
    """Load the metrics files and write all Chapter 7 LaTeX tables."""
    comparison = json.loads((METRICS / "comparison_test.json").read_text(encoding="utf-8"))
    diagnostics = json.loads((METRICS / "ch7_diagnostics.json").read_text(encoding="utf-8"))
    reference: dict[str, dict[str, float]] = {}
    for line in (METRICS / "paper_reference.csv").read_text(encoding="utf-8").splitlines()[1:]:
        approach, metric, value = line.split(",")
        reference.setdefault(approach.removesuffix("_val"), {})[metric] = float(value)
    families = {tuple(f["pairs"]) for f in comparison["verdicts"]["families"]}
    for needed in (
        ("rag:baseline", "sft:baseline", "dual_agent:baseline"),
        ("gan/final:baseline", "gan/final:dual_agent"),
        ("triple_agent/final:gan/final",),
    ):
        if needed not in families:
            raise SystemExit(
                f"comparison_test.json lacks the family {needed} -- rerun the aggregator"
            )
    src = "comparison_test.json + ch7_diagnostics.json"
    tables = {
        "ch7_tab_overview.tex": tab_overview(comparison, reference),
        "ch7_tab_secondary.tex": tab_secondary(comparison),
        "ch7_tab_rq1_pairs.tex": tab_rq1_pairs(comparison),
        "ch7_tab_hand_check.tex": tab_hand_check(diagnostics),
        "ch7_tab_loop_validation.tex": tab_loop_validation(diagnostics),
        "ch7_tab_rq2.tex": tab_rq2(comparison),
        "ch7_tab_rq3.tex": tab_rq3(comparison),
        "ch7_tab_rq3_stages.tex": tab_rq3_stages(comparison, diagnostics),
        "ch7_tab_cost.tex": tab_cost(comparison, diagnostics),
        "ch7_tab_per_cwe_f1.tex": tab_per_cwe_f1(comparison),
        "ch7_app_memories.tex": app_memories(diagnostics),
    }
    for name, body in tables.items():
        (METRICS / name).write_text(HEADER.format(src=src) + body, encoding="utf-8")
        print(f"wrote {METRICS / name}")


if __name__ == "__main__":
    main()
