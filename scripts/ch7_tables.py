    """MCC and predicted-positive rate of the six approaches."""
    rows = [
        r"\begin{tabular}{@{}lcc@{}}",
        r"\toprule",
        r"Approach & MCC & PPR \\",
        r"\midrule",
    ]
    for name in ALL:
        if name == "gan/final":
            rows.append(r"\midrule")
        sec = c["approaches"][name]["secondary"]["macro"]
        rows.append(f"{NAMES[name]} & {ms(sec['mcc'])} & {ms(sec['pred_positive_rate'])} \\\\")
