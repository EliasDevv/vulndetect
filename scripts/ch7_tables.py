def ms(cell: dict, digits: int = 3) -> str:
    """Format a cell as mean ± sd, or the single value when there is one seed."""
    if cell["std"] is None:
        return f"{cell['mean']:.{digits}f}"
    return f"{cell['mean']:.{digits}f}\\,$\\pm$\\,{cell['std']:.{digits}f}"


def pval(p: float) -> str:
    """Format a p-value for LaTeX, printing values below 0.001 as a bound."""
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def pair_entry(comparison: dict, x: str, y: str) -> tuple[dict, str]:
    """Return the verdict of a pair in either order and the name of the favoured side."""
    for v in comparison["verdicts"]["pairs"]:
        if (v["a"], v["b"]) in ((x, y), (y, x)):
            favoured = {"a>b": v["a"], "b>a": v["b"]}.get(v["direction"])
            return v, NAMES[favoured] if favoured else v["direction"]
    raise KeyError(f"no verdict for {x}:{y}")


def mcnemar_counts(comparison: dict, x: str, y: str) -> dict[int, tuple[int, int]]:
    """Return per seed (x correct & y wrong, x wrong & y correct)."""
    out = {}
    for m in comparison["mcnemar"]:
        if "skipped" in m:
            continue
        if (m["a"], m["b"]) == (x, y):
            out[m["seed"]] = (m["n_a_correct_b_wrong"], m["n_a_wrong_b_correct"])
        elif (m["a"], m["b"]) == (y, x):
            out[m["seed"]] = (m["n_a_wrong_b_correct"], m["n_a_correct_b_wrong"])
    return out


def ttest(comparison: dict, x: str, y: str) -> dict:
    """Return the paired t-test of x against y, flipping the sign if stored as y against x."""
    for t in comparison["ttests"]:
        if (t["a"], t["b"]) == (x, y):
            return t
        if (t["a"], t["b"]) == (y, x):
            return {**t, "t": -t["t"], "mean_diff": -t["mean_diff"]}
    raise KeyError(f"no t-test for {x}:{y}")


def tab_overview(c: dict, reference: dict[str, dict[str, float]]) -> str:
    """Main results of the six approaches on the test split, with the paper's values below."""
    metrics = ("f1", "accuracy", "precision", "recall")
    rows = [
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r"Approach & F1 & Acc. & Prec. & Rec. \\",
        r"\midrule",
    ]
    for name in ALL:
        if name == "gan/final":
            rows.append(r"\midrule")
        a = c["approaches"][name]
        rows.append(f"{NAMES[name]} & " + " & ".join(ms(a["macro"][m]) for m in metrics) + r" \\")
    rows.append(r"\midrule")
    for name in RQ1:
        ref = reference.get(name, {})
        cells = [f"{ref[m]:.2f}" if m in ref else "--" for m in metrics]
        rows.append(f"{NAMES[name]} (paper) & " + " & ".join(cells) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


