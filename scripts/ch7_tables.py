HAND_CHECK_CATEGORIES = (
    ("intended", "plausibly contains an instance of the assigned weakness class"),
    ("other", "contains a weakness of a different class"),
    ("broken", "is defective without anything exploitable"),
    ("none", "is equivalent to its source or differs only cosmetically"),
)


def tab_hand_check(d: dict) -> str:
    """Hand-check table: cases per category and the in-loop verdicts."""
    hc = d["hand_check"]
    counts, flagged = hc["counts"], hc["detector_vulnerable_by_category"]
    rows = [
        r"\begin{tabular}{@{}l>{\raggedright\arraybackslash}p{0.46\textwidth}cc@{}}",
        r"\toprule",
        r"Category & The generated function \ldots & Cases & "
        r"\begin{tabular}[b]{@{}c@{}}Judged \emph{Vulnerable}\\in the loop\end{tabular} \\",
        r"\midrule",
    ]
    for key, meaning in HAND_CHECK_CATEGORIES:
        rows.append(f"\\emph{{{key}}} & {meaning} & {counts[key]} & {flagged[key]} \\\\")
    if sum(counts.values()) != hc["n"]:
        raise ValueError("hand-check categories do not add up to the sample size")
    rows += [
        r"\midrule",
        f"Total & & {hc['n']} & {sum(flagged.values())} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    return "\n".join(rows)


def tab_loop_validation(d: dict) -> str:
    """Gate rejections, pass-through rate and self-reflection accuracy per loop run."""

    def head(a: str, b: str) -> str:
        return r"\begin{tabular}[b]{@{}c@{}}" + a + r"\\" + b + r"\end{tabular}"

    rows = [
        r"\begin{tabular}{@{}llccc@{}}",
        r"\toprule",
        "Loop & Seed & "
        + head("Rejected", "by the gate")
        + " & "
        + head(r"Judged \emph{Not}", r"\emph{Vulnerable}")
        + " & "
        + head("Self-reflection", "accuracy")
        + r" \\",
        r"\midrule",
    ]
    loops = (
        ("GAN (RQ2)", d["loop_stats"]),
        ("Triple-Agent (RQ3)", d["triple_agent"]["loop_stats"]),
    )
    for k, (label, ls) in enumerate(loops):
        if k:
            rows.append(r"\midrule")
        for i, seed in enumerate(sorted(ls)):
            gate, passed, refl = ls[seed]["gate"], ls[seed]["pass_through"], ls[seed]["phase_b"]
            rows.append(
                f"{label if i == 0 else ''} & {seed} & "
                f"{100 * gate['rejected_share']:.0f}\\,\\% & "
                f"{100 * passed['final_rate']:.1f}\\,\\% & "
                f"{refl['accuracy']:.3f} \\\\"
            )
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


